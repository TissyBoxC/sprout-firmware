#!/usr/bin/env python3
"""Bind a production PlatformIO build to secure_version.txt."""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

Import("env")  # noqa: F821 - provided by SCons


def _secure_version() -> int:
    project_dir = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    value = (
        project_dir.joinpath("secure_version.txt")
        .read_text(encoding="utf-8")
        .strip()
    )
    if not re.fullmatch(r"[1-9][0-9]*", value):
        raise ValueError(
            "secure_version.txt must contain one positive integer"
        )
    version = int(value)
    if version > 65535:
        raise ValueError("secure_version.txt exceeds the ESP32-S3 limit")
    return version


if env.subst("$PIOENV").endswith("-production"):  # noqa: F821
    project_dir = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    try:
        secure_version = _secure_version()
    except (OSError, ValueError) as error:
        sys.stderr.write(f"\nError: {error}.\n")
        env.Exit(1)  # noqa: F821

    overlay = project_dir / "sdkconfig.secure-version.generated"
    overlay.write_text(
        "# Generated by prepare_production_secure_version.py. "
        "Do not commit.\n"
        f"CONFIG_BOOTLOADER_APP_SECURE_VERSION={secure_version}\n",
        encoding="utf-8",
        newline="\n",
    )

    option = env.GetProjectOption(  # noqa: F821
        "board_build.cmake_extra_args",
        "",
    )
    match = re.search(r'-DSDKCONFIG_DEFAULTS="([^"]+)"', option)
    if match is None:
        sys.stderr.write(
            "\nError: production build must define "
            'board_build.cmake_extra_args=-DSDKCONFIG_DEFAULTS="..."\n'
        )
        env.Exit(1)  # noqa: F821
    defaults = [
        item.strip()
        for item in match.group(1).split(";")
        if item.strip()
    ]
    overlay_text = os.fspath(overlay)
    if overlay_text not in defaults:
        defaults.append(overlay_text)
    generated = ";".join(defaults)
    generated_for_cmake = (
        generated.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "$$")
    )
    env.BoardConfig().update(  # noqa: F821
        "build.cmake_extra_args",
        f'-DSDKCONFIG_DEFAULTS="{generated_for_cmake}"',
    )
